  const cell = (item,row,col,identity,matrix) => {
    const id = `obe-tip-${matrix}-${row}-${col}`;
    const rationale = `${identity}: ${t(labels[item.level])}. ${item[lang]}`;
    return `<td><button type="button" class="obe-cell level-${item.level}" aria-expanded="false" aria-controls="${id}" aria-describedby="${id}" aria-label="${esc(rationale)}"><span aria-hidden="true">${symbols[item.level]}</span></button><span id="${id}" class="obe-tip" role="tooltip" hidden>${esc(rationale)}</span></td>`;
  };
  const legend = `<p class="obe-legend">${labels.map((key,i)=>`<span><b aria-hidden="true">${symbols[i]}</b> ${tr(key)}</span>`).reverse().join('')}</p>`;
