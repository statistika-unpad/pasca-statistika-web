  const tr = key => esc(t(key));
  const text = (key,tag='p',attrs='') => `<${tag} ${attrs}>${tr(key)}</${tag}>`;
  const names = ['academicianTitle','researcherTitle','consultantTitle','practitionerTitle'];
  const code = j => `${lang === 'en' ? 'PLO' : 'CPL'}-${j+1}`;
